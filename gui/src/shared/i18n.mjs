export function translate(text,language='en'){
  if(language!=='zh')return text;
  if(zh[text])return zh[text];
  if(text.endsWith('…') && zh[text.slice(0,-1)+'.'])return zh[text.slice(0,-1)+'.'].replace(/。$/,'…');
  const rules=[
    [/^Adaptation: (.*)$/,(_,v)=>'适配：'+translate(v,language)],
    [/^Active: (.*) · (Follow Codex|Force light skin|Force dark skin)$/,(_,n,v)=>'已应用：'+n+' · '+translate(v,language)],
    [/^Actions for (.*)$/,(_,n)=>n+' 的操作'],
    [/^Delete “(.*)”\?$/,(_,n)=>'删除“'+n+'”？'],
    [/^(v.*) · (user|builtin|development|unknown)$/,(_,v,o)=>v+' · '+({user:'用户',builtin:'内置',development:'开发测试',unknown:'未知'}[o])],
    [/^by (.*)$/,(_,n)=>'作者：'+n],
    [/^(\d+) invalid packages?$/,(_,n)=>n+' 个无效主题包'],
    [/^Ready\. (\d+) invalid packages? (?:was|were) isolated\.$/,(_,n)=>'就绪。已隔离 '+n+' 个无效主题包。'],
    [/^This theme supports (Dark|Light) Codex appearance only\. Follow Codex will fail closed when Codex uses the unsupported appearance\.$/,(_,v)=>'此主题仅支持 Codex '+translate(v,language)+'外观。跟随 Codex 时，遇到不支持的外观会安全停止。'],
  ];
  for(const [pattern,replace] of rules)if(pattern.test(text))return text.replace(pattern,replace);
  return text;
}
